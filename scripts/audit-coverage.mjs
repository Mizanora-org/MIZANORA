/*
 * Mizanora v56 — "kaun se page khali hain?" ka jawab, file mein.
 *
 * Reads the two committed data files and reports:
 *   data/imdb-ids.txt   every URL the sitemap advertises (id, type, year)
 *   data/imdb-seed.json the titles that render WITHOUT internet
 *
 * Writes COVERAGE.md (a human report + a CSV of the empty ids next to it) and prints a summary.
 * Nothing is guessed: if a title is not in the seed, it is marked "live IMDb par depend".
 *
 * Run: npm run coverage
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const idsFile = path.join(root, 'data', 'imdb-ids.txt');
const seedFile = path.join(root, 'data', 'imdb-seed.json');

const readIds = () => {
  if (!fs.existsSync(idsFile)) return [];
  return fs.readFileSync(idsFile, 'utf8')
    .split('\n')
    .filter(Boolean)
    .map((line) => {
      const [id, type, year] = line.split('\t');
      return { id: String(id || '').trim(), type: type === 'series' ? 'series' : 'movie', year: Number(year) || 0 };
    })
    .filter((x) => /^tt\d{6,10}$/.test(x.id));
};

const readSeed = () => {
  if (!fs.existsSync(seedFile)) return { movies: [], series: [] };
  const data = JSON.parse(fs.readFileSync(seedFile, 'utf8'));
  return { movies: data.movies || [], series: data.series || [] };
};

const ids = readIds();
const seed = readSeed();
const have = new Set([...seed.movies, ...seed.series].map((m) => m.i));
const seeded = ids.filter((x) => have.has(x.id));
const missing = ids.filter((x) => !have.has(x.id));

const byDecade = new Map();
for (const x of ids) {
  const decade = x.year ? Math.floor(x.year / 10) * 10 : 0;
  const row = byDecade.get(decade) || { total: 0, seeded: 0 };
  row.total += 1;
  if (have.has(x.id)) row.seeded += 1;
  byDecade.set(decade, row);
}

const pct = (a, b) => (b ? Math.round((a / b) * 1000) / 10 : 0);
const fmt = (n) => Number(n || 0).toLocaleString('en-US');
const movies = ids.filter((x) => x.type !== 'series');
const series = ids.filter((x) => x.type === 'series');
const seededMovies = movies.filter((x) => have.has(x.id));
const seededSeries = series.filter((x) => have.has(x.id));

const csv = ['id,type,year,status', ...ids.map((x) => `${x.id},${x.type},${x.year || ''},${have.has(x.id) ? 'data' : 'live-only'}`)].join('\n');
fs.writeFileSync(path.join(root, 'coverage-ids.csv'), csv);

const decadeRows = [...byDecade.entries()]
  .filter(([d]) => d > 0)
  .sort((a, b) => a[0] - b[0])
  .map(([d, r]) => `| ${d}s | ${fmt(r.total)} | ${fmt(r.seeded)} | ${pct(r.seeded, r.total)}% |`);

const doc = `# Coverage report — kaun se page bhare hue hain

Generated by \`npm run coverage\` on ${new Date().toISOString().slice(0, 10)}.

| Cheez | Count |
| --- | --- |
| Sitemap URLs (movies + series) | **${fmt(ids.length)}** |
| Movies | ${fmt(movies.length)} (${fmt(seededMovies.length)} bhare hue) |
| Series | ${fmt(series.length)} (${fmt(seededSeries.length)} bhare hue) |
| Committed snapshot (internet ke baghair) | **${fmt(seeded.length)}** |
| Live IMDb par depend | **${fmt(missing.length)}** |
| Bhare hue pages | **${pct(seeded.length, ids.length)}%** |

## Decade ke hisaab se

| Decade | URLs | Snapshot mein | Coverage |
| --- | --- | --- | --- |
${decadeRows.join('\n')}

## Iska matlab

* **${fmt(seeded.length)}** pages har haal mein chalte hain (server apna data rakhta hai).
* **${fmt(missing.length)}** pages ka poster/cast/story live IMDb (Cinemeta/TMDB) se aata hai. Wahan
  jawab na aaye to page "data pending" ban jata hai — useful, magar adhoora, aur \`noindex\`.
* Isi liye do modes hain:
  * \`SITEMAP_DATA_ONLY=1\` → index sirf ${fmt(seeded.length)} bhare hue titles list karta hai (safest).
  * full pool (default) → sab ${fmt(ids.length)} titles, live IMDb par bharosa.

## Poori list

Har id ki status \`coverage-ids.csv\` mein hai (columns: id, type, year, data | live-only).
Admin panel mein bhi yehi numbers \`/sitemaps\` par "Coverage" card mein dikhte hain.
`;

fs.writeFileSync(path.join(root, 'COVERAGE.md'), doc);

console.log('coverage report');
console.log(`  sitemap ids      ${fmt(ids.length)}  (${fmt(movies.length)} movies, ${fmt(series.length)} series)`);
console.log(`  with data        ${fmt(seeded.length)}  (${pct(seeded.length, ids.length)}%)`);
console.log(`  live-IMDb only   ${fmt(missing.length)}`);
console.log('  wrote COVERAGE.md and coverage-ids.csv');
